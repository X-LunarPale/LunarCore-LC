import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parseMinecraftText, shouldPreviewField, numberMetadata } from './minecraft-text.js'

const plain = result => result.segments.map(segment => segment.text).join('')
const parse = parseMinecraftText
let result = parse('<red>A<bold>B</bold>C</red>D')
assert.equal(plain(result), 'ABCD')
assert.equal(result.segments[0].style.color, '#ff5555')
assert.equal(result.segments[1].style.fontWeight, '700')
assert.equal(result.segments[2].style.fontWeight, undefined)
assert.equal(result.segments.at(-1).style.color, undefined)
assert.equal(parse('<#12abef>X').segments[0].style.color, '#12abef')
assert.equal(parse('<color:gold>X</color>').segments[0].style.color, '#ffaa00')
assert.equal(parse('<italic><underlined><strikethrough>X').segments[0].style.textDecorationLine, 'underline line-through')
assert.equal(parse('<italic>X<reset>Y').segments.at(-1).style.fontStyle, undefined)
assert.equal(parse('<bold>X<bold:false>Y</bold>Z').segments[1].style.fontWeight, undefined)
assert.equal(parse('<bold>X<!bold>Y</bold>Z').segments[1].style.fontWeight, undefined)
result = parse('<gradient:red:blue>ABC</gradient>')
assert.deepEqual(result.segments.map(item => item.style.color), ['#ff5555', '#aa55aa', '#5555ff'])
assert.equal(plain(parse('<gradient:#ff0000:#00ff00:#0000ff>😀中a</gradient>')), '😀中a')
assert.equal(new Set(parse('<rainbow>abcdef</rainbow>').segments.map(item => item.style.color)).size > 3, true)
assert.equal(plain(parse('<rainbow:!2>abc</rainbow>')), 'abc')
assert.equal(parse('&aA§lB&rC').segments[1].style.fontWeight, '700')
assert.equal(parse('&aA§lB&rC').segments.at(-1).style.color, undefined)
assert.equal(parse('&#abcdefX').segments[0].style.color, '#abcdef')
assert.equal(parse('§x§1§2§3§4§5§6X').segments[0].style.color, '#123456')
assert.equal(parse('&x&1&2&3&4&5&6X').segments[0].style.color, '#123456')
for (const input of ['<click:run_command:/op user>X</click>', '<hover:show_text:hi>X</hover>', '<img src=x onerror=alert(1)>', '<script>alert(1)</script>', '<red onclick=evil()>', '<gradient:red:invalid>X', '<#nope>', '</green>', '<rainbow:NaN>', '<rainbow:>', '<red', '&ksecret', '&#xyz']) {
  result = parse(input)
  assert.ok(result.warnings.length, `warning expected: ${input}`)
  assert.equal(plain(result), input)
  for (const segment of result.segments) assert.deepEqual(segment.style, {})
}
result = parse('<green>{online}/{max} {version} {unknown}', { online: 0, max: 100, version: '<img onerror=evil()>' })
assert.equal(plain(result), '0/100 <img onerror=evil()> {unknown}')
assert.deepEqual(result.unresolved, ['unknown'])
assert.equal(result.warnings.length, 0, 'variables must be literal, never reparsed')
assert.deepEqual(parse('{online}/{max}').unresolved, ['online', 'max'])
assert.equal(plain(parse('{online}', { online: NaN })), '{online}')
assert.equal(plain(parse('\\<red>X')), '<red>X')
assert.ok(parse('\u0000').warnings.length)
assert.ok(plain(parse('x'.repeat(20000))).length <= 16384)
for (const field of [{ key: 'motd' }, { name: 'announcement' }, { id: 'welcomeMessage' }, { label: '服务器简介' }, { key: 'line1', preview: true }]) assert.equal(shouldPreviewField(field), true)
for (const field of [{ key: 'title' }, { key: 'username' }, { key: 'motd', preview: false }, { type: 'password', key: 'motd', preview: true }, { key: 'broadcastCommands', preview: true }, { key: 'motdUrl' }, { label: '通知邮箱', preview: true }, { type: 'code', preview: true }]) assert.equal(shouldPreviewField(field), false)
assert.deepEqual(numberMetadata({ min: 0, max: 10, step: 0.25 }), { min: 0, max: 10, step: 0.25, bounded: true })
assert.equal(numberMetadata({ min: '', max: 10 }).bounded, false)
assert.equal(numberMetadata({ min: 10, max: 0 }).bounded, false)
assert.equal(numberMetadata({ min: 0, max: Infinity }).bounded, false)
assert.equal(numberMetadata({ min: 0, max: 1, step: 0 }).step, 1)
const component = readFileSync(new URL('./MinecraftTextPreview.vue', import.meta.url), 'utf8')
assert.equal(component.includes('v-html'), false)
assert.match(component, /\{\{ segment\.text \}\}/)
for (const input of ['<gradient:constructor:red>AB', '<gradient:__proto__:red>AB', '<constructor>X</constructor>']) {
  assert.doesNotThrow(() => parse(input))
  assert.ok(parse(input).warnings.length)
}
assert.equal(plain(parse('&a欢迎', {}, { legacy: false })), '&a欢迎')
result = parse('<gradient:red:blue>{online}X</gradient>', { online: 100 }, { atomicVariables: true, legacy: false })
assert.deepEqual(result.segments.map(s => [s.text, s.style.color]), [['100', '#ff5555'], ['X', '#5555ff']])
console.log('Text preview: parser, styles, variables, hostile input, field eligibility, and numeric metadata checks passed.')
